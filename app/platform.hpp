// Services the UI needs from the operating system. The Windows implementation lives in
// platform/win32; the Linux development harness has a stand-in that detects nothing.
#pragma once

#include <cstdint>
#include <filesystem>
#include <optional>
#include <string>
#include <utility>
#include <vector>

#include "fit/profile.hpp"
#include "fit/windows_checks.hpp"

namespace fitapp {

// ---- raw mouse input ----------------------------------------------------------------------------

struct MouseDevice {
    std::string id;        // stable hash of the device interface path
    std::string name;      // product string when available
    std::string vid_pid;   // "046D:C094" or empty
    std::string path;      // \\?\HID#VID_046D&PID_C094...
    bool absolute = false; // tablets, remote desktop, VMs: not usable for calibration
};

enum RawButton : uint16_t { kLeftDown = 1, kLeftUp = 2, kRightDown = 4, kRightUp = 8 };

struct RawEvent {
    int64_t t_us = 0;         // same clock as IRawMouse::now_us()
    int32_t dx = 0, dy = 0;   // counts; +x right, +y toward the user
    uint16_t buttons = 0;     // RawButton flags
    std::string device_id;    // empty for software-injected input
    bool injected = false;    // generated by software (SendInput etc.) — never used for measurement
    bool absolute = false;
};

class IRawMouse {
public:
    virtual ~IRawMouse() = default;
    // Starts capturing raw mouse reports for this window only. Capture stops by itself when the
    // window loses focus; stop() releases it immediately.
    virtual bool start(std::string* error) = 0;
    virtual void stop() = 0;
    virtual bool active() const = 0;
    virtual void drain(std::vector<RawEvent>& out) = 0;
    virtual std::vector<MouseDevice> devices() = 0;
    virtual std::optional<MouseDevice> device(const std::string& id) = 0;
    virtual int64_t now_us() const = 0;
    // Increments whenever a mouse is connected or removed.
    virtual uint64_t device_change_counter() const = 0;
};

// ---- displays -----------------------------------------------------------------------------------

struct DisplayInfo {
    std::string device;        // \\.\DISPLAY1
    std::string name;          // monitor friendly name
    std::string edid_id;       // manufacturer + product code
    std::string connector;     // "DisplayPort", "HDMI", ...
    int width = 0, height = 0;
    double refresh_hz = 0.0;
    std::vector<double> modes_hz;  // refresh rates at the current resolution
    bool primary = false;
    bool hosts_window = false;
    std::string ddcci = "unknown";  // "supported" | "unsupported" | "unknown"
    std::string ddcci_note;
    bool vrr_hint = false;     // only a hint; not reliably detectable
};

// ---- frame presentation ------------------------------------------------------------------------

enum class RenderMode {
    Ui,          // vsync, power friendly
    MouseTest,   // low latency: no vsync (tearing allowed if supported), capped by a precise limiter
    MotionTest,  // exactly one new frame per refresh (vsync), with dropped-frame detection
};

struct FrameTiming {
    double last_interval_ms = 0.0;
    double refresh_hz = 0.0;
    bool tearing_supported = false;
    uint64_t dropped_frames = 0;  // MotionTest: presents that missed their refresh
    double limiter_fps = 0.0;
};

// ---- PresentMon -------------------------------------------------------------------------------

struct PresentMonStatus {
    bool available = false;
    std::string path;
    std::string note;  // e.g. how to get it, privilege requirements
};

struct CaptureRequest {
    std::string process_name = "VALORANT-Win64-Shipping.exe";
    int duration_s = 60;
    int delay_s = 0;            // wait before recording
    std::string hotkey;         // e.g. "F10": start recording on key press (PresentMon's own hotkey)
    std::filesystem::path output_csv;
    bool elevate = false;       // ask Windows for administrator rights (UAC)
};

enum class CaptureState { Idle, Waiting, Recording, Finished, Failed };

struct CaptureStatus {
    CaptureState state = CaptureState::Idle;
    std::string message;
    std::filesystem::path csv;  // when Finished
    double elapsed_s = 0.0;
};

class IPresentMon {
public:
    virtual ~IPresentMon() = default;
    virtual PresentMonStatus status() = 0;
    virtual void set_path(const std::string& path) = 0;
    virtual bool start(const CaptureRequest& req, std::string* error) = 0;
    virtual CaptureStatus poll() = 0;
    virtual void cancel() = 0;
};

// ---- platform ---------------------------------------------------------------------------------

class IPlatform {
public:
    virtual ~IPlatform() = default;
    virtual std::string name() const = 0;          // "Windows 11 (build 22631)" / "Linux development harness"
    virtual bool dev_harness() const = 0;           // true: nothing here is a measurement of real hardware
    virtual std::filesystem::path data_dir() = 0;

    virtual IRawMouse& mouse() = 0;
    virtual IPresentMon& presentmon() = 0;

    virtual fit::PcInfo detect_pc() = 0;
    virtual std::vector<DisplayInfo> displays() = 0;
    // Temporarily switch the refresh rate of a display (reverts when FitSuite exits).
    virtual bool set_refresh_temporary(const std::string& device, double hz, std::string* error) = 0;
    virtual bool restore_display(const std::string& device, std::string* error) = 0;
    // Persistent change (written to the Windows display settings). The UI asks the player to
    // confirm within 15 seconds and reverts otherwise.
    virtual bool set_refresh_persistent(const std::string& device, double hz, std::string* error) = 0;

    virtual bool window_focused() const = 0;
    virtual void set_cursor_captured(bool captured) = 0;
    virtual void set_fullscreen(bool fullscreen) = 0;
    virtual void set_render_mode(RenderMode mode, double limiter_fps = 0.0) = 0;
    virtual FrameTiming frame_timing() const = 0;

    virtual std::optional<std::filesystem::path> open_file_dialog(const std::string& title, const std::string& filter_desc,
                                                                  const std::string& pattern) = 0;
    virtual std::optional<std::filesystem::path> save_file_dialog(const std::string& title, const std::string& default_name,
                                                                  const std::string& filter_desc, const std::string& pattern) = 0;
    virtual void open_folder(const std::filesystem::path& p) = 0;
    virtual void open_url(const std::string& url) = 0;

    // Asks the monitor over DDC/CI whether it answers (talks to the monitor, can take a few seconds,
    // so it only runs when the player asks). Returns "supported", "unsupported" or "unknown".
    virtual std::string probe_ddcci(const std::string& device) { return "unknown"; }

    // Starts a helper program without a console window and returns a token (0 = not started).
    // FitSuite uses this only for Raw Accel's own writer.exe, when the player asks.
    virtual uint64_t start_program(const std::filesystem::path& exe, const std::vector<std::filesystem::path>& args,
                                   std::string* error) {
        if (error) *error = "Running other programs is not available here.";
        return 0;
    }
    // Exit code once the program has finished; std::nullopt while it is still running.
    virtual std::optional<int> program_exit_code(uint64_t token) { return -1; }

    // Executable name (lower case) of the program in front, e.g. "valorant-win64-shipping.exe";
    // "" if unknown. Only the name is read; FitSuite never opens or inspects the game itself.
    virtual std::string foreground_app() { return ""; }
    // Programs that have a visible window: (executable name, window title). Used to pick a game.
    virtual std::vector<std::pair<std::string, std::string>> running_apps() { return {}; }
    // "Open FitSuite when Windows starts": one per-user startup entry.
    virtual bool autostart_enabled() { return false; }
    // Windows can switch a startup entry off without removing it (Task Manager → Startup apps →
    // Disable). FitSuite respects that and only reports it...
    virtual bool autostart_blocked() { return false; }
    // ...unless the player ticks "Open FitSuite when Windows starts" again: then it is switched back on.
    virtual void unblock_autostart() {}
    virtual bool set_autostart(bool on, std::string* error) {
        if (error) *error = "Not available here.";
        return false;
    }
    // While on, closing the window keeps FitSuite running in the notification area (system tray).
    virtual void set_keep_running(bool on) {}

    // Windows' app mode (Settings → Personalization → Colors): true = dark, nullopt = unknown.
    virtual std::optional<bool> system_dark_mode() { return std::nullopt; }
    // Light or dark window title bar, to match FitSuite's theme.
    virtual void set_dark_title_bar(bool dark) {}

    virtual bool rawaccel_driver_present() = 0;
    virtual std::string rawaccel_settings_hint() = 0;  // where settings.json usually is, if known

    // ---- setup and updates --------------------------------------------------------------------
    // Downloads run in the background, only when the player asks (setup: Raw Accel) or for the
    // update check they switched on. HTTPS only.
    struct DownloadStatus {
        bool done = false;
        bool ok = false;
        uint64_t bytes = 0, total = 0;  // total 0 = unknown
        std::string error;
    };
    virtual uint64_t start_download(const std::string& url, const std::filesystem::path& dest, std::string* error) {
        if (error) *error = "Downloads are not available here.";
        return 0;
    }
    virtual DownloadStatus download_status(uint64_t token) {
        DownloadStatus s;
        s.done = true;
        s.error = "Downloads are not available here.";
        return s;
    }
    virtual void cancel_download(uint64_t token) {}
    // Unpacks a .zip into a folder. Token for program_exit_code.
    virtual uint64_t start_unzip(const std::filesystem::path& zip, const std::filesystem::path& dest, std::string* error) {
        if (error) *error = "Unpacking is not available here.";
        return 0;
    }
    // Runs a program with administrator rights; Windows asks the player first. Token for program_exit_code.
    virtual uint64_t start_elevated(const std::filesystem::path& exe, std::string* error) {
        if (error) *error = "Not available here.";
        return 0;
    }
    // Folders that look like an unpacked Raw Accel (they contain writer.exe), best guess first.
    virtual std::vector<std::filesystem::path> find_rawaccel_folders() { return {}; }
    // Raw Accel needs the Visual C++ runtime; true when it is installed (or unknown).
    virtual bool vc_runtime_installed() { return true; }
    // Where the setup unpacks programs for this user (%LOCALAPPDATA%\Programs).
    virtual std::filesystem::path programs_dir() { return data_dir() / "programs"; }
    // FitSuite.exe itself.
    virtual std::filesystem::path self_exe() { return {}; }
    // Swaps in a downloaded and checked FitSuite.exe and starts it; the caller then quits FitSuite.
    virtual bool apply_update(const std::filesystem::path& new_exe, std::string* error) {
        if (error) *error = "Updating is not available here.";
        return false;
    }
    // A few Windows settings that matter for games, read only (Settings → Windows settings for games).
    virtual fit::WindowsGameSettings windows_game_settings() { return {}; }
    // Ends FitSuite (as if "Quit" was chosen in the notification area).
    virtual void request_quit() {}
    // Restarts Windows in 5 seconds (after the player confirmed), to finish a driver install.
    virtual bool restart_pc(std::string* error) {
        if (error) *error = "Not available here.";
        return false;
    }
};

}  // namespace fitapp
